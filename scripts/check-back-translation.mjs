#!/usr/bin/env node
/**
 * Blind back-translation check for body-part tiles.
 *
 * The acoustic checker (check-spoken-collisions.mjs) proves two tiles SOUND
 * different. It cannot prove they MEAN the right thing. Two failures it lets
 * through:
 *
 *   - a tile that is pronounced perfectly but names the wrong body part
 *     (Swahili Heel shipped as "Kisvisvi", not a word at all);
 *   - two tiles that sound distinct yet both land on the same concept
 *     (Bengali গোড়ালির গাঁট and গোড়ালি would both be understood as the heel).
 *
 * Method: show a model ONLY the foreign word and ask which English body part
 * it names. It is never told what we expect, never shown the tile id, and the
 * words are shuffled so neighbouring tiles cannot cue each other. Then:
 *
 *   MISMATCH  — back-translation != the English tile it is supposed to render
 *   COLLISION — two tiles in one language back-translate to the same English
 *
 * KNOWN LIMITATION, stated because it bounds what this proves: most of these
 * translations were generated by Gemini, and this check queries Gemini. For
 * those, agreement is partly self-confirming — it catches gross errors and
 * word-sense slips, not shared blind spots. It is genuinely independent only
 * for the handful of words chosen by a different reviewer (bn Ankle/Arm, am
 * Foot, ro Throat, ja Foot), which is exactly the set it was built to settle.
 *
 * Neither this nor the acoustic check replaces a native speaker.
 *
 *   GEMINI_API_KEY=... node scripts/check-back-translation.mjs
 *   node scripts/check-back-translation.mjs --langs=bn,am,ja --verbose
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const KEY = process.env.GEMINI_API_KEY || '';
if (!KEY) {
  console.error('GEMINI_API_KEY is not set.');
  process.exit(1);
}

const MODEL = 'gemini-3.6-flash';
const API_URL = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent`;

const args = new Map(process.argv.slice(2).map((a) => {
  const [k, v] = a.replace(/^--/, '').split('=');
  return [k, v ?? true];
}));

const LANG_NAMES = {
  ro: 'Romanian', es: 'Spanish', fr: 'French', pt: 'Portuguese', de: 'German',
  ru: 'Russian', uk: 'Ukrainian', ja: 'Japanese', ko: 'Korean', zh: 'Chinese',
  ar: 'Arabic', hi: 'Hindi', it: 'Italian', pl: 'Polish', he: 'Hebrew',
  nl: 'Dutch', vi: 'Vietnamese', tl: 'Filipino', tr: 'Turkish', id: 'Indonesian',
  bg: 'Bulgarian', am: 'Amharic', sw: 'Swahili', bn: 'Bengali',
};

const RE_ENTRY = /^\s*'([^']+)':\s*\{(.*)\}\s*,?\s*$/gm;
const RE_LANG = /(?:^|[,{])\s*'?([a-zA-Z-]{2,7})'?\s*:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")/g;
const unesc = (s) => s.replace(/\\(['"\\])/g, '$1');

const T = {};
for (const m of fs.readFileSync(path.join(ROOT, 'constants/phraseTranslations.ts'), 'utf-8').matchAll(RE_ENTRY)) {
  const L = {};
  for (const lm of m[2].matchAll(RE_LANG)) L[lm[1]] = unesc(lm[2] ?? lm[3]);
  T[m[1]] = L;
}

const phraseSrc = fs.readFileSync(path.join(ROOT, 'constants/phrases.ts'), 'utf-8');
const EN = {};
for (const m of phraseSrc.matchAll(/^\s*p\(\s*'([^']+)'\s*,\s*'([^']+)'\s*,\s*(?:'((?:[^'\\]|\\.)*)'|"([^"]*)")/gm)) {
  EN[m[1]] = { cat: m[2], text: unesc(m[3] ?? m[4]) };
}

/**
 * Actual body PARTS only.
 *
 * The `health-body` category also contains symptoms (Fever, Chills), events
 * (Doctor visit, X-ray), objects (EpiPen, Inhaler) and actions (Brush my
 * teeth). The first version of this script globbed the whole category and
 * asked "which body part is this?" of every one of them, so ~180 of its 187
 * "mismatches" were the model correctly answering UNKNOWN to a false premise.
 *
 * A check that cries wolf is worse than no check — it trains you to skim the
 * output, which is how the two genuine findings in that run (bn hbp-foot, the
 * hbp-leg collision) nearly got lost. So the list is explicit.
 */
const NOT_BODY_PARTS = new Set([
  'hurts', 'sick', 'medicine', 'headache', 'stomachache', 'earache', 'toothache',
  'sore-throat', 'cough', 'sneeze', 'runny-nose', 'stuffy-nose', 'fever', 'chills',
  'shaking', 'dizzy-spell', 'bruise', 'cut', 'scrape', 'bump', 'bandage',
  'itchy-spot', 'rash', 'allergic-reaction', 'pain', 'sharp-pain', 'dull-pain',
  'burning', 'vitamins', 'inhaler', 'epipen', 'pill', 'drops', 'doctor-visit',
  'shot', 'x-ray', 'check-up', 'wash-my-hands', 'brush-my-teeth',
]);
const TILES = Object.keys(EN).filter((id) => {
  if (!/^(hb|hbp)-/.test(id) || !/body/.test(EN[id].cat)) return false;
  return !NOT_BODY_PARTS.has(id.replace(/^hbp?-/, ''));
});

// Read PERMITTED_COLLAPSES from the contract rather than restating it, so this
// script and CI cannot disagree about what is allowed to share a meaning.
const contractSrc = fs.readFileSync(path.join(ROOT, 'constants/bodyPartDistinctions.ts'), 'utf-8');
const permittedBlock = contractSrc.slice(contractSrc.indexOf('PERMITTED_COLLAPSES'));
const PERMITTED = [...permittedBlock.matchAll(/a: '([^']+)',\s*\n\s*b: '([^']+)'/g)]
  .map((m) => [m[1], m[2]].sort().join('|'));
const isPermitted = (a, b) => PERMITTED.includes([a, b].sort().join('|'));

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function ask(prompt) {
  for (let i = 0; i < 4; i++) {
    try {
      const r = await fetch(API_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'x-goog-api-key': KEY },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: {
            temperature: 0, maxOutputTokens: 8192,
            thinkingConfig: { thinkingLevel: 'minimal' },
            responseMimeType: 'application/json',
          },
        }),
      });
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      const j = await r.json();
      return JSON.parse(j.candidates[0].content.parts[0].text);
    } catch (e) {
      if (i === 3) throw e;
      await sleep(2 ** i * 1000);
    }
  }
}

/**
 * Deterministic shuffle so neighbouring tiles never appear in tile order and
 * cannot cue each other, while keeping runs reproducible.
 */
function shuffled(arr, seed) {
  const a = [...arr];
  let s = seed;
  for (let i = a.length - 1; i > 0; i--) {
    s = (s * 1103515245 + 12345) & 0x7fffffff;
    const j = s % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

const only = args.get('langs') ? String(args.get('langs')).split(',') : null;
const langs = Object.keys(LANG_NAMES).filter((l) => !only || only.includes(l));
const verbose = args.has('verbose');

console.log('Blind back-translation check — body-part tiles');
console.log(`${langs.length} language(s), ${TILES.length} tiles each\n`);

const mismatches = [];
const collisions = [];

for (const lang of langs) {
  const present = TILES.filter((id) => T[id]?.[lang]);
  if (!present.length) continue;

  // Ask about unique WORDS, not tiles: identical strings on two tiles is the
  // acoustic checker's job, and asking twice would just burn tokens.
  const byWord = new Map();
  for (const id of present) {
    const w = T[id][lang];
    if (!byWord.has(w)) byWord.set(w, []);
    byWord.get(w).push(id);
  }
  const words = shuffled([...byWord.keys()], lang.charCodeAt(0) * 7919);

  const prompt = `Below is a numbered list of ${LANG_NAMES[lang]} words or short phrases. Each one names a part of the human body.

For each, answer with the single most natural ENGLISH name for that body part — the word an ordinary English speaker would use (e.g. "hand", "arm", "foot", "leg", "heel", "ankle", "throat", "neck", "lips", "mouth").

Rules:
- Judge ONLY the word given. There is no context and you must not guess from position in the list.
- Use the most specific English body part it actually denotes. If it means the sole of the foot, say "sole", not "foot".
- If it is not a real ${LANG_NAMES[lang]} word, or you cannot identify a body part, answer exactly "UNKNOWN".
- Lowercase, one or two words maximum.

Return ONLY a JSON object mapping each number to your answer.

${words.map((w, i) => `${i + 1}. ${w}`).join('\n')}`;

  let out;
  try {
    out = await ask(prompt);
  } catch (e) {
    console.log(`  ${lang}: FAILED (${e.message}) — not checked`);
    continue;
  }

  const heard = new Map(); // english -> [tile ids]
  for (const [i, w] of words.entries()) {
    const got = String(out[String(i + 1)] ?? out[i + 1] ?? '').trim().toLowerCase();
    for (const id of byWord.get(w)) {
      const want = EN[id].text.toLowerCase();
      const ok = got === want
        // Accept a documented near-equivalence: several languages have no word
        // for the foot proper and use "sole", which we already accept for
        // he/id/bn/ja. Treating that as a mismatch would be noise.
        || (want === 'foot' && (got === 'sole' || got === 'sole of the foot'))
        || (want === 'toe' && got === 'toes')
        || (want === 'finger' && got === 'fingers')
        || (want === 'lips' && got === 'lip')
        || (want === 'eyes' && got === 'eye')
        || (want === 'ears' && got === 'ear')
        || (want === 'teeth' && got === 'tooth')
        // English synonyms — the tile word and the natural back-translation
        // differ without either being wrong.
        || (want === 'tummy' && (got === 'stomach' || got === 'belly' || got === 'abdomen'))
        || (want === 'belly' && (got === 'stomach' || got === 'tummy' || got === 'abdomen'))
        || (want === 'bottom' && (got === 'buttocks' || got === 'buttock' || got === 'butt' || got === 'bum'))
        || (want === 'knuckle' && got === 'knuckles')
        || (want === 'hair' && got === 'head hair')
        // DELIBERATE: several languages use one word for hand+arm (рука,
        // ръка, mkono), so the Hand tile was moved to the palm-word to make
        // Hand and Arm distinguishable — Кисть/Длан/Долоня/Kiganja. Back-
        // translating to "palm" is the design working, not a defect. Same
        // shape as accepting "sole" for Foot above.
        || (want === 'hand' && (got === 'palm' || got === 'palm of the hand'));
      if (!ok) {
        mismatches.push({ lang, id, said: w, want: EN[id].text, got });
        console.log(`  ${lang} ${id}: "${w}" reads as "${got}" — tile is "${EN[id].text}"`);
      } else if (verbose) {
        console.log(`  ${lang} ${id}: "${w}" -> "${got}" ok`);
      }
      if (got && got !== 'unknown') {
        if (!heard.has(got)) heard.set(got, []);
        heard.get(got).push(id);
      }
    }
  }

  for (const [eng, ids] of heard) {
    const uniqueEnglish = new Set(ids.map((id) => EN[id].text.toLowerCase()));
    // Tiles that are ALLOWED to collapse (English synonyms, singular/plural)
    // are not findings — reporting them trains the reader to skim.
    const allPermitted = ids.every((a) =>
      ids.every((b) => a === b || isPermitted(a, b)));
    if (ids.length > 1 && uniqueEnglish.size > 1 && !allPermitted) {
      collisions.push({ lang, english: eng, ids });
      console.log(`  ${lang} SEMANTIC COLLISION: ${ids.join(' + ')} all mean "${eng}"`);
    }
  }
}

console.log(`\n${mismatches.length} mismatch(es), ${collisions.length} semantic collision(s)`);
if (mismatches.length || collisions.length) {
  console.log('\nA mismatch means the tile speaks a word for a different body part.');
  console.log('A semantic collision means two tiles land on the same concept, so the');
  console.log('user still cannot say which part hurts even if the words sound different.');
}
process.exitCode = mismatches.length || collisions.length ? 1 : 0;
