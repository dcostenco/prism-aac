const LEGACY_DB_NAME = 'prism-aac-pictograms';
const LEGACY_MISSES_KEY = 'prism-arasaac-misses';
const LEGACY_CLEARED_KEY = 'prism-legacy-pictograms-cleared';
const CLEANUP_VERSION = '2';
const ARASAAC_DOMAIN = 'arasaac.org';
let cleanup: Promise<void> | null = null;

function isRetiredSource(url: string): boolean {
  const host = new URL(url).hostname.toLowerCase();
  return host === ARASAAC_DOMAIN || host.endsWith(`.${ARASAAC_DOMAIN}`);
}

async function removeHttpEntries(): Promise<void> {
  if (typeof caches === 'undefined') return;
  for (const name of await caches.keys()) {
    const cache = await caches.open(name);
    for (const request of await cache.keys()) {
      if (isRetiredSource(request.url)) await cache.delete(request);
    }
  }
}

/**
 * The retired database mixed third-party and older generated bytes without
 * provenance. Neither is read by the current client. Retire that namespace;
 * keep the separate current generated-picture DB and local picture pack.
 * Old tabs may block deletion: completion is marked only after they close.
 */
export function clearLegacyPictogramCache(): Promise<void> {
  if (typeof window === 'undefined') return Promise.resolve();
  if (cleanup) return cleanup;
  const run = async () => {
    localStorage.removeItem(LEGACY_MISSES_KEY);
    const deletion = new Promise<void>((resolve, reject) => {
      const request = indexedDB.deleteDatabase(LEGACY_DB_NAME);
      request.onsuccess = () => resolve();
      request.onerror = () => reject(request.error);
      request.onblocked = () => console.warn('Retired picture cache cleanup is waiting for an older tab to close');
    });
    await Promise.all([deletion, removeHttpEntries()]);
    localStorage.setItem(LEGACY_CLEARED_KEY, CLEANUP_VERSION);
  };
  cleanup = run().catch(error => {
    console.warn('Retired picture cache cleanup did not complete', error instanceof Error ? error.message : 'storage error');
    throw error;
  }).finally(() => { cleanup = null; });
  return cleanup;
}
